package net.christianbeier.droidvnc_ng

/**
 * Translates RFB keysyms into Unicode code points for text entry.
 */
object InputKeysymToUnicode {

    /*
        Legacy X11/RFB keysym -> Unicode code point for Cyrillic. RFB clients
        (e.g. noVNC) send these 0x06xx keysyms for Cyrillic, NOT the 0x01000000+
        Unicode range, so without this map Cyrillic input is silently dropped.
        Generated as the inverse of noVNC's keysymdef codepoints table.
     */
    private val KEYSYM_UNICODE = mapOf(
        0x06b3 to 0x0401, 0x06b1 to 0x0402, 0x06b2 to 0x0403, 0x06b4 to 0x0404,
        0x06b5 to 0x0405, 0x06b6 to 0x0406, 0x06b7 to 0x0407, 0x06b8 to 0x0408,
        0x06b9 to 0x0409, 0x06ba to 0x040a, 0x06bb to 0x040b, 0x06bc to 0x040c,
        0x06be to 0x040e, 0x06bf to 0x040f, 0x06e1 to 0x0410, 0x06e2 to 0x0411,
        0x06f7 to 0x0412, 0x06e7 to 0x0413, 0x06e4 to 0x0414, 0x06e5 to 0x0415,
        0x06f6 to 0x0416, 0x06fa to 0x0417, 0x06e9 to 0x0418, 0x06ea to 0x0419,
        0x06eb to 0x041a, 0x06ec to 0x041b, 0x06ed to 0x041c, 0x06ee to 0x041d,
        0x06ef to 0x041e, 0x06f0 to 0x041f, 0x06f2 to 0x0420, 0x06f3 to 0x0421,
        0x06f4 to 0x0422, 0x06f5 to 0x0423, 0x06e6 to 0x0424, 0x06e8 to 0x0425,
        0x06e3 to 0x0426, 0x06fe to 0x0427, 0x06fb to 0x0428, 0x06fd to 0x0429,
        0x06ff to 0x042a, 0x06f9 to 0x042b, 0x06f8 to 0x042c, 0x06fc to 0x042d,
        0x06e0 to 0x042e, 0x06f1 to 0x042f, 0x06c1 to 0x0430, 0x06c2 to 0x0431,
        0x06d7 to 0x0432, 0x06c7 to 0x0433, 0x06c4 to 0x0434, 0x06c5 to 0x0435,
        0x06d6 to 0x0436, 0x06da to 0x0437, 0x06c9 to 0x0438, 0x06ca to 0x0439,
        0x06cb to 0x043a, 0x06cc to 0x043b, 0x06cd to 0x043c, 0x06ce to 0x043d,
        0x06cf to 0x043e, 0x06d0 to 0x043f, 0x06d2 to 0x0440, 0x06d3 to 0x0441,
        0x06d4 to 0x0442, 0x06d5 to 0x0443, 0x06c6 to 0x0444, 0x06c8 to 0x0445,
        0x06c3 to 0x0446, 0x06de to 0x0447, 0x06db to 0x0448, 0x06dd to 0x0449,
        0x06df to 0x044a, 0x06d9 to 0x044b, 0x06d8 to 0x044c, 0x06dc to 0x044d,
        0x06c0 to 0x044e, 0x06d1 to 0x044f, 0x06a3 to 0x0451, 0x06a1 to 0x0452,
        0x06a2 to 0x0453, 0x06a4 to 0x0454, 0x06a5 to 0x0455, 0x06a6 to 0x0456,
        0x06a7 to 0x0457, 0x06a8 to 0x0458, 0x06a9 to 0x0459, 0x06aa to 0x045a,
        0x06ab to 0x045b, 0x06ac to 0x045c, 0x06ae to 0x045e, 0x06af to 0x045f,
        0x06bd to 0x0490, 0x06ad to 0x0491, 0x06b0 to 0x2116,
    )

    /**
     * Translate an RFB keysym to a Unicode code point for text entry,
     * or -1 if it is not a printable-character keysym we can type.
     */
    @JvmStatic
    fun keysymToUnicode(keysym: Long): Int {
        if (keysym in 0x20L..0xffL)
            return keysym.toInt()                             // Latin-1 (keysym == code point)
        KEYSYM_UNICODE[keysym.toInt()]?.let { return it }     // legacy Cyrillic keysym
        if (keysym in 0x01000000L..0x0110ffffL)
            return (keysym - 0x01000000L).toInt()             // RFB Unicode keysym
        return -1
    }
}